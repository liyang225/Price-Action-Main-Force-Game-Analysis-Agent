def replace_paragraph_text(paragraph, text):
    """Replace a paragraph while retaining its paragraph style and first-run formatting."""
    if paragraph.runs:
        first = paragraph.runs[0]
        first.text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


